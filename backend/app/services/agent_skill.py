"""Portable Agent Skill export.

ONCE stores personal methods as structured records. This module turns one
record into the portable folder format AI agents understand: a ``SKILL.md``
with YAML frontmatter plus an optional JSON manifest. The agent can copy the
folder into its own skills directory and load it later.

The export is read-only and uses the same authorization as every other read:
the caller must own the skill or hold a non-revoked share grant.
"""
from __future__ import annotations

import io
import json
import re
import zipfile

from app.models.core import Skill, SkillType

FORMAT = "once-agent-skill-v1"


def slugify(title: str) -> str:
    """A stable, agent-friendly skill name derived from the human title."""
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    slug = re.sub(r"-{2,}", "-", slug)[:64].strip("-")
    return slug or "once-skill"


def skill_description(skill: Skill) -> str:
    summary = (skill.summary or "").strip()
    if not summary:
        summary = f"A personal method called {skill.title}, saved in ONCE."
    if skill.type == SkillType.packing:
        use = "Use it when the user asks what to pack or what they are missing."
    elif skill.type == SkillType.desktop_workflow:
        use = "Use it when the user asks how to find or open something in a desktop app."
    elif skill.type == SkillType.browser_workflow:
        use = "Use it when the user asks how to complete this browser workflow."
    elif skill.type == SkillType.household_procedure:
        use = "Use it when the user asks how to do this household task."
    else:
        use = "Use it when the user asks about this personal checklist."
    description = f"{summary} {use}"
    return description[:1024]


def _items_section(skill: Skill) -> str:
    if not skill.items:
        return ""
    lines = ["## Required items", ""]
    for item in skill.items:
        aliases = f" (also called: {', '.join(item.aliases)})" if item.aliases else ""
        required = "" if item.required else " (optional)"
        lines.append(f"- {item.name}{aliases}{required}")
    lines.extend(
        [
            "",
            (
                "Ask which items the user already has. Report every required item "
                "that is not confirmed as **not confirmed**, never as definitely "
                "missing."
            ),
        ]
    )
    return "\n".join(lines)


def _steps_section(skill: Skill) -> str:
    if not skill.steps:
        return ""
    lines = ["## Steps", ""]
    for index, step in enumerate(sorted(skill.steps, key=lambda s: s.order), start=1):
        location = f" On: {step.screen}." if step.screen else ""
        lines.append(f"{index}. {step.instruction}{location}")
    return "\n".join(lines)


def render_skill_md(skill: Skill) -> str:
    """Render one stored skill as a portable ``SKILL.md`` document."""
    name = slugify(skill.title)
    description = skill_description(skill)
    summary = (skill.summary or "").strip() or "A personal method saved in ONCE."
    body = [
        "---",
        f"name: {name}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
        "---",
        "",
        f"# {skill.title}",
        "",
        summary,
        "",
        "## How to use this skill",
        "",
        "- Answer from the stored method below. Do not invent extra items or steps.",
        (
            "- If the user asks to change the method, ask for explicit confirmation "
            "before saving a new version."
        ),
        "- If the stored record does not cover the request, say so instead of guessing.",
    ]
    items = _items_section(skill)
    if items:
        body.extend(["", items])
    steps = _steps_section(skill)
    if steps:
        body.extend(["", steps])
    body.extend(
        [
            "",
            "## Source",
            "",
            f"- ONCE skill: `{skill.skill_id}`",
            f"- Type: `{skill.type.value}`",
            f"- Version: `{skill.version}`",
            f"- Taught via: `{skill.source.value}`",
            "",
            "<!-- Generated by ONCE. The structured record remains the source of truth. -->",
            "",
        ]
    )
    return "\n".join(body)


def manifest(skill: Skill) -> dict:
    """Machine-readable companion for agents that prefer JSON over YAML."""
    return {
        "format": FORMAT,
        "name": slugify(skill.title),
        "title": skill.title,
        "description": skill_description(skill),
        "type": skill.type.value,
        "version": skill.version,
        "source": skill.source.value,
        "summary": skill.summary,
        "items": [
            {
                "name": item.name,
                "required": item.required,
                "aliases": item.aliases,
            }
            for item in skill.items
        ],
        "steps": [
            {
                "order": step.order,
                "instruction": step.instruction,
                "screen": step.screen,
            }
            for step in sorted(skill.steps, key=lambda s: s.order)
        ],
        "skill_id": skill.skill_id,
    }


def render_bundle(skill: Skill) -> bytes:
    """Return a zip containing ``<slug>/SKILL.md`` and ``once-skill.json``."""
    name = slugify(skill.title)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(f"{name}/SKILL.md", render_skill_md(skill))
        archive.writestr(
            f"{name}/once-skill.json",
            json.dumps(manifest(skill), ensure_ascii=False, indent=2) + "\n",
        )
    return buffer.getvalue()
